#!/usr/bin/env python3
"""Regenerate platform palette files from palette/tokens.json.

Writes:
  android/app/src/main/gen/dev/ngale/thirds/Palette.kt

Usage: scripts/sync_palette.py [--check]   (--check: verify only)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "palette" / "tokens.json"


def argb(color: str) -> int:
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})", color)
    if m:
        return 0xFF000000 | int(m.group(1), 16)
    m = re.fullmatch(r"rgba\((\d+),(\d+),(\d+),([\d.]+)\)", color)
    if not m:
        raise ValueError(f"bad colour {color!r}")
    alpha = round(float(m.group(4)) * 255)
    return alpha << 24 | int(m.group(1)) << 16 | int(m.group(2)) << 8 | int(m.group(3))


def hx(v: int) -> str:
    lit = f"0x{v:08X}"
    return f"{lit}.toInt()" if v > 0x7FFFFFFF else lit


def kotlin_scheme(tokens: dict) -> str:
    def period(p: str, ap: str) -> str:
        t = tokens["periods"][p][ap]
        return (f"PeriodColors(fill = {hx(argb(t['fill']))}, "
                f"sheen = {hx(argb(t['sheen']))}, edge = {hx(argb(t['edge']))})")

    def glass(ap: str) -> str:
        t = tokens["glass"][ap]
        return f"Glass(body = {hx(argb(t['body']))}, hairline = {hx(argb(t['hairline']))})"

    out = []
    for ap in ("dark", "light"):
        out.append(
            f"    val {ap.upper()} = Scheme(\n"
            f"        day = {period('day', ap)},\n"
            f"        evening = {period('evening', ap)},\n"
            f"        night = {period('night', ap)},\n"
            f"        glass = {glass(ap)},\n"
            f"    )")
    return "\n\n".join(out)


def render_kotlin(tokens: dict) -> str:
    return (
        "// Generated by scripts/sync_palette.py from palette/tokens.json — do not edit.\n"
        "package dev.ngale.thirds\n\n"
        "object Palette {\n"
        "    data class PeriodColors(val fill: Int, val sheen: Int, val edge: Int)\n"
        "    data class Glass(val body: Int, val hairline: Int)\n"
        "    data class Scheme(\n"
        "        val day: PeriodColors,\n"
        "        val evening: PeriodColors,\n"
        "        val night: PeriodColors,\n"
        "        val glass: Glass,\n"
        "    )\n\n"
        + kotlin_scheme(tokens) + "\n}\n"
    )


def render_shape(color: str, stroke: str | None) -> str:
    def android_hex(c: str) -> str:
        return f"#{argb(c):08X}"  # Android wants #AARRGGBB
    color = android_hex(color)
    stroke = android_hex(stroke) if stroke else None
    stroke_xml = ""
    if stroke:
        stroke_xml = f'\n    <stroke android:width="1dp" android:color="{stroke}" />'
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/sync_palette.py — do not edit. -->\n"
        '<shape xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:shape="rectangle">\n'
        f'    <solid android:color="{color}" />{stroke_xml}\n'
        '    <corners android:radius="9dp" />\n'
        "</shape>\n"
    )


def targets(tokens: dict):
    yield (ROOT / "android/app/src/main/gen/dev/ngale/thirds/Palette.kt",
           render_kotlin(tokens))

    dark = {p: tokens["periods"][p]["dark"] for p in ("day", "evening", "night")}
    g = tokens["glass"]["dark"]
    res = ROOT / "android/app/src/main/res/drawable"
    for p in dark:
        yield (res / f"fill_{p}.xml", render_shape(dark[p]["fill"], dark[p]["edge"]))
    yield (res / "glass_pill.xml", render_shape(g["body"], g["hairline"]))


def main() -> int:
    check = "--check" in sys.argv
    tokens = json.loads(TOKENS.read_text())
    assert tokens["format"] == "thirds-palette/1", tokens["format"]
    drift = []
    for path, content in targets(tokens):
        if check:
            if not path.exists() or path.read_text() != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if drift:
        print("PALETTE DRIFT (stale, run scripts/sync_palette.py):", *drift, sep="\n  ")
        return 1
    print("ok" if check else "synced")
    return 0


if __name__ == "__main__":
    sys.exit(main())
